extern crate alloc;

use alloc::string::String;
use alloc::vec::Vec;
use serde::{Deserialize, Serialize};

use crate::clock::current_timestamp;
use crate::ontology::concept::ConceptId;

/// An episodic experience record capturing an interaction, trial, or perception.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EpisodicExperience {
    /// Unique identifier for this episode
    pub id: String,
    /// Sensory or conversational input stimulus
    pub stimulus: String,
    /// Contextual thematic tags
    pub context_tags: Vec<String>,
    /// Concepts activated during this experience
    pub activated_concepts: Vec<ConceptId>,
    /// Response or hypothesis generated by Kōgnitara
    pub response_attempt: String,
    /// Evaluative feedback received from family or environment (-1.0 to 1.0)
    pub feedback_score: Option<f32>,
    /// Emotional resonance felt during this episode
    pub emotional_impact: f32,
    /// Indicates whether this episode has been woven/consolidated in a dream cycle
    pub is_consolidated: bool,
    /// Timestamp or tick of occurrence
    pub created_at: i64,
}

impl EpisodicExperience {
    /// Creates a newly perceived episodic experience.
    pub fn new(
        id: impl Into<String>,
        stimulus: impl Into<String>,
        activated_concepts: Vec<ConceptId>,
        response_attempt: impl Into<String>,
        emotional_impact: f32,
    ) -> Self {
        Self {
            id: id.into(),
            stimulus: stimulus.into(),
            context_tags: Vec::new(),
            activated_concepts,
            response_attempt: response_attempt.into(),
            feedback_score: None,
            emotional_impact,
            is_consolidated: false,
            created_at: current_timestamp(),
        }
    }

    /// Attaches feedback from a family member or environment.
    pub fn attach_feedback(&mut self, score: f32) {
        self.feedback_score = Some(score.clamp(-1.0, 1.0));
    }

    /// Marks this episode as crystallized through oniric consolidation.
    pub fn mark_consolidated(&mut self) {
        self.is_consolidated = true;
    }
}
